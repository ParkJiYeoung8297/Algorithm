SELECT bookA.AUTHOR_ID, bookA.AUTHOR_NAME, bookA.CATEGORY, sum(bookA.PRICE*saleA.SALES_COUNT) as TOTAL_SALES
FROM (
    SELECT a.AUTHOR_ID, a.AUTHOR_NAME, b.BOOK_ID, b.CATEGORY, b.PRICE
    FROM AUTHOR as a
    JOIN BOOK as b ON a.AUTHOR_ID = b.AUTHOR_ID) as bookA
JOIN (
    SELECT BOOK_ID, SUM(SALES) as SALES_COUNT
    FROM BOOK_SALES
    WHERE SALES_DATE >= '2022-01-01' AND SALES_DATE <= '2022-01-31'
    GROUP BY BOOK_ID) as saleA
ON bookA.BOOK_ID = saleA.BOOK_ID
GROUP BY bookA.AUTHOR_ID, bookA.AUTHOR_NAME, bookA.CATEGORY
ORDER BY bookA.AUTHOR_ID ASC, bookA.CATEGORY DESC;
